namespace TrainingBitwiseOperators
{
    internal class Program
    {
        static void Main(string[] args)
        {
            Console.WriteLine("Hello, World!");


            // AND &
            //  OR |
            // XOR ^
            // NEG ~

            int a = 2;
            int b = 3;

            Console.WriteLine(a & b);
            Console.WriteLine(a | b);
            Console.WriteLine(a ^ b);
            Console.WriteLine(~a);
        }
    }
}
